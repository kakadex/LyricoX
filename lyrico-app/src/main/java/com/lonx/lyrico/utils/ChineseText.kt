    /** 繁转简；无对应映射的字原样保留。 */
    fun toSimplified(text: String?): String {
        if (text == null || text.isEmpty()) return ""
        var s: String = text
        for (i in TRAD_PHRASES.indices) {
            if (s.contains(TRAD_PHRASES[i])) {
                s = s.replace(TRAD_PHRASES[i], SIMP_PHRASES[i])
            }
        }
        val sb = StringBuilder(s.length)
        for (c in s) {
            sb.append(TRAD_CHARS[c] ?: c)
        }
        return sb.toString()
    }
